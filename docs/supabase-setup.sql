-- ============================================================
-- 6. POLICIES DOS UTILIZADORES
-- ============================================================

-- Todos os utilizadores autenticados podem consultar perfis.
CREATE POLICY "Utilizadores autenticados podem ler perfis" ON public.users
  FOR SELECT TO authenticated
  USING (TRUE);

-- Um utilizador so pode criar um perfil associado a sua conta Auth.
CREATE POLICY "Utilizador cria o proprio perfil" ON public.users
  FOR INSERT TO authenticated
  WITH CHECK (auth_id = auth.uid());

-- USING controla quais linhas existentes podem ser atualizadas.
-- WITH CHECK valida como a linha pode ficar depois da atualizacao.
CREATE POLICY "Utilizador atualiza o proprio perfil" ON public.users
  FOR UPDATE TO authenticated
  USING (auth_id = auth.uid())
  WITH CHECK (auth_id = auth.uid());


-- ============================================================
-- 7. POLICIES DAS MOEDAS
-- ============================================================

-- Todos os utilizadores autenticados podem consultar moedas.
CREATE POLICY "Utilizadores autenticados podem ler moedas" ON public.coins
  FOR SELECT TO authenticated
  USING (TRUE);

-- So e possivel criar uma moeda com owner_id igual ao perfil do utilizador atualmente autenticado.
CREATE POLICY "Utilizador cria moedas proprias" ON public.coins
  FOR INSERT TO authenticated
  WITH CHECK (EXISTS (
    SELECT
      1
    FROM
      public.users
    WHERE
      users.id = coins.owner_id
      AND users.auth_id = auth.uid()));

-- Apenas o proprietario pode atualizar a moeda.
CREATE POLICY "Utilizador atualiza moedas proprias" ON public.coins
  FOR UPDATE TO authenticated
  USING (EXISTS (
    SELECT
      1
    FROM
      public.users
    WHERE
      users.id = coins.owner_id
      AND users.auth_id = auth.uid()))
  WITH CHECK (EXISTS (
    SELECT
      1
    FROM
      public.users
    WHERE
      users.id = coins.owner_id
      AND users.auth_id = auth.uid()));

-- Apenas o proprietario pode eliminar a moeda.
CREATE POLICY "Utilizador remove moedas proprias" ON public.coins
  FOR DELETE TO authenticated
  USING (EXISTS (
    SELECT
      1
    FROM
      public.users
    WHERE
      users.id = coins.owner_id
      AND users.auth_id = auth.uid()));


-- ============================================================
-- 8. POLICIES DAS CONVERSAS
-- ============================================================

-- Apenas o comprador e o vendedor podem consultar a conversa.
CREATE POLICY "Participantes podem ler conversas" ON public.conversations
  FOR SELECT TO authenticated
  USING (EXISTS (
    SELECT
      1
    FROM
      public.users
    WHERE
      users.auth_id = auth.uid()
      AND (users.id = conversations.buyer_id
      OR users.id = conversations.seller_id)));

-- So o utilizador identificado como comprador pode criar a conversa.
CREATE POLICY "Comprador cria conversa propria" ON public.conversations
  FOR INSERT TO authenticated
  WITH CHECK (EXISTS (
    SELECT
      1
    FROM
      public.users
    WHERE
      users.id = conversations.buyer_id
      AND users.auth_id = auth.uid()));

-- O comprador e o vendedor podem atualizar a conversa, por exemplo, para adicionar mensagens ou alterar o estado da negociacao.
CREATE POLICY "Participantes atualizam conversas" ON public.conversations
  FOR UPDATE TO authenticated
  USING (EXISTS (
    SELECT
      1
    FROM
      public.users
    WHERE
      users.auth_id = auth.uid()
      AND (users.id = conversations.buyer_id
      OR users.id = conversations.seller_id)))
  WITH CHECK (EXISTS (
    SELECT
      1
    FROM
      public.users
    WHERE
      users.auth_id = auth.uid()
      AND (users.id = conversations.buyer_id
      OR users.id = conversations.seller_id)));


