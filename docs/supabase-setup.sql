-- ============================================================
-- 1. TABELAS PRINCIPAIS
-- ============================================================

-- Perfis publicos dos utilizadores da aplicacao.
-- auth_id liga este perfil ao utilizador criado pelo Supabase Auth.
-- rating e total_reviews sao atualizados automaticamente por um trigger.
CREATE TABLE public.users(
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  auth_id uuid UNIQUE REFERENCES auth.users(id) ON DELETE CASCADE,
  name text NOT NULL,
  email text NOT NULL UNIQUE,
  location text NOT NULL,
  rating numeric DEFAULT 0 NOT NULL,
  total_reviews integer DEFAULT 0 NOT NULL
);

-- Moedas adicionadas pelos utilizadores.
-- photos guarda uma lista de URLs em formato JSON.
CREATE TABLE public.coins(
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  name text NOT NULL,
  origin text NOT NULL,
  year text NOT NULL,
  material text NOT NULL,
  condition text NOT NULL,
  description text NOT NULL,
  photos jsonb DEFAULT '[]'::jsonb NOT NULL,
  available_for_sale boolean DEFAULT FALSE NOT NULL,
  available_for_trade boolean DEFAULT FALSE NOT NULL,
  price numeric,
  trade_preference text,
  created_at timestamptz DEFAULT now() NOT NULL,
  updated_at timestamptz DEFAULT now() NOT NULL
);

-- Conversas/negociacoes entre um comprador e um vendedor.
-- As mensagens sao guardadas como uma lista JSON no campo messages.
CREATE TABLE public.conversations(
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  coin_id bigint NOT NULL REFERENCES public.coins(id) ON DELETE CASCADE,
  buyer_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  seller_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  status text DEFAULT 'aberta' NOT NULL,
  messages jsonb DEFAULT '[]'::jsonb NOT NULL,
  created_at timestamptz DEFAULT now() NOT NULL,
  updated_at timestamptz DEFAULT now() NOT NULL
);

-- Avaliacoes feitas no contexto de uma conversa.
-- reviewer_id identifica quem avaliou.
-- reviewed_user_id identifica quem recebeu a avaliacao.
CREATE TABLE public.reviews(
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversation_id bigint NOT NULL REFERENCES public.conversations(id) ON DELETE CASCADE,
  reviewer_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  reviewed_user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  stars integer NOT NULL,
  comment text NOT NULL,
  created_at timestamptz DEFAULT now() NOT NULL
);


-- ============================================================
-- 2. INDICES E RESTRICOES DE UNICIDADE
-- ============================================================

-- Impede que exista mais do que uma negociacao aberta para a mesma moeda, com o mesmo comprador e vendedor.
CREATE UNIQUE INDEX conversations_unique_open_negotiation ON public.conversations(coin_id, buyer_id, seller_id)
WHERE
  status = 'aberta';

-- Cada utilizador so pode fazer uma avaliacao por conversa.
CREATE UNIQUE INDEX reviews_unique_per_conversation_reviewer ON public.reviews(conversation_id, reviewer_id);


-- ============================================================
-- 3. CRIACAO AUTOMATICA DO PERFIL DO UTILIZADOR
-- ============================================================

-- Funcao executada quando uma conta e criada no Supabase Auth.
-- SECURITY DEFINER faz a funcao usar as permissoes de quem a criou, permitindo inserir o perfil mesmo com RLS ativa.
CREATE OR REPLACE FUNCTION public.handle_new_user()
  RETURNS TRIGGER
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path = public
  AS $$
BEGIN
  -- NEW representa o novo registo criado na tabela auth.users.
  INSERT INTO public.users(auth_id, name, email, location)
    VALUES(NEW.id, COALESCE(NEW.raw_user_meta_data ->> 'name', split_part(NEW.email, '@', 1)), NEW.email, COALESCE(NEW.raw_user_meta_data ->> 'location', 'Por definir'))
  ON CONFLICT(auth_id)
    DO NOTHING;
  RETURN new;
END;
$$;

-- Depois de inserir uma conta em auth.users, cria o perfil em public.users.
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW
  EXECUTE FUNCTION public.handle_new_user();


-- ============================================================
-- 4. ATUALIZACAO AUTOMATICA DAS AVALIACOES
-- ============================================================

-- Recalcula o rating medio e o numero de reviews do utilizador avaliado.
CREATE OR REPLACE FUNCTION public.update_user_rating_from_reviews()
  RETURNS TRIGGER
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path = public
  AS $$
DECLARE
  target_user_id bigint;
BEGIN
  -- NEW existe num INSERT/UPDATE e OLD existe num DELETE.
  -- COALESCE escolhe o valor que estiver disponivel.
  target_user_id := COALESCE(NEW.reviewed_user_id, OLD.reviewed_user_id);
  UPDATE
    public.users
  SET
    rating = COALESCE((
      SELECT
        round(avg(stars)::numeric, 1)
      FROM public.reviews
      WHERE
        reviewed_user_id = target_user_id), 0), total_reviews =(
      SELECT
        count(*)
      FROM
        public.reviews
      WHERE
        reviewed_user_id = target_user_id)
  WHERE
    id = target_user_id;
  RETURN COALESCE(new, old);
END;
$$;

-- Executa a funcao sempre que uma review e criada, editada ou eliminada.
CREATE TRIGGER on_review_changed
  AFTER INSERT OR UPDATE OR DELETE ON public.reviews
  FOR EACH ROW
  EXECUTE FUNCTION public.update_user_rating_from_reviews();


